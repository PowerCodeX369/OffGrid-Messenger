const assert=require('node:assert/strict');
const {webcrypto}=require('node:crypto');
globalThis.crypto=webcrypto;
const P=require('../web/protocol.js');
(async()=>{
 assert.equal(P.types.probe,5);
 assert.equal(P.types.probeAck,6);
 const key=await P.importKey(P.randomBytes(32));
 const probeId=P.newId(),transferId=P.newId();
 const body=P.randomBytes(8192);
 const envelope=P.makeEnvelope(P.types.probe,probeId,body);
 const sealed=await P.seal(key,envelope,transferId);
 const parts=P.frames(transferId,sealed);
 assert(parts.length>=50);
 const parsed=parts.map(p=>P.parseFrame(p));
 assert(parsed.every(p=>p&&p.count===parts.length));
 assert(parsed.every((p,i)=>p.index===i));
 const rejoined=P.concat(...parsed.map(p=>p.bytes));
 assert.deepEqual(rejoined,sealed);
 const opened=P.parseEnvelope(await P.open(key,rejoined,transferId));
 assert.equal(opened.kind,P.types.probe);
 assert.equal(opened.id,probeId);
 assert.deepEqual(opened.body,body);
 const ack=P.makeEnvelope(P.types.probeAck,P.newId(),P.unhex(probeId));
 const ackSealed=await P.seal(key,ack,P.newId());
 assert(ackSealed.length>0);
 const tampered=sealed.slice();tampered[tampered.length-1]^=1;
 await assert.rejects(P.open(key,tampered,transferId));
 console.log('PASS encrypted 8 KiB benchmark, fragment reassembly, final ACK type, tamper rejection');
})().catch(e=>{console.error(e);process.exit(1)});
